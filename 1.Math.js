/*
Math -> Matemática
    - pow(2,2) / potência / 2² = 4
    -sqrt(25,2) / raiz / √25
    - PI / 3,14
    - ceil / teto -> Arredondar para cima
    - floor / chão -> Arrendondar para baixo

    - random() / número aleatório entre 0 e 1
*/

// pow

const resultado = Math.pow(5,2)         // Potência (5*5)
console.log(resultado)

// sqrt

const resultado2 = Math.sqrt(25)      // Raiz quadrada
console.log(resultado2)

// Pi

const resultado3 = Math.PI              // Valor de PI
console.log(resultado3)

// ceil 

const resultado4 = Math.ceil(3.5)       // Arredondar para cima
console.log(resultado4)

// floor 

const resultado5 = Math.floor(3.5)      // Arrendondar para baixo
console.log(resultado5)

// random

const resultado6 = Math.random()     // Gera um número aleatório entre 0 e 1
console.log(resultado6)