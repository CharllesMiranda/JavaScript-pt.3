/*
    Operadores de Atribuição

     = -> Atribuição
    += -> Adição
    -= -> Subtração
    /= -> Divisão
    *= -> Multiplicação
    %= -> Resto

*/

//  =  -> Atribuição
const atribuicao = 20

//  += -> Adição
let adicao = 20
adicao += 70    // Mesma coisa de colocar "adicao = adicao + 70"

//  -= -> Subtração
let subtracao = 20
subtracao -= 50    // Mesma coisa de colocar "subtracao = subtracao - 50"

//  /= -> Divisão
let divisao = 20
divisao /= 2    // Mesma coisa de colocar "divisao = divisao / 2"

//  *= -> Multiplicação

let multiplicacao = 20
multiplicacao *= 5    // Mesma coisa de colocar "multiplicacao = multiplicacao * 5"

//  %= -> Resto
let resto = 20
resto %= 3    // Mesma coisa de colocar "resto = resto % 3"
