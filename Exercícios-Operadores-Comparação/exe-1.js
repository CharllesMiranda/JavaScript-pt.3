/**

Exercício 1 — Comparação simples

Crie duas variáveis:

let idade1 = 18
let idade2 = 20

Faça comparações usando > e < para descobrir:
    Se idade1 é maior que idade2
    Se idade1 é menor que idade2

Mostre os resultados no console.

*/

let idade1 = 18
let idade2 = 20

// Se idade1 é maior que idade2

