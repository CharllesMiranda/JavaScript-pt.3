/*
Operadores Aritméticos

+  -> Adição
-  -> Subtração
/  -> Divisão
*  -> Multiplicação
%  -> Resto
++ -> Incremento
-- -> Decremento
** -> Exponencial

*/

// +  -> Adição

const adicao = 2 + 2

// -  -> Subtração

const subtracao = 5 - 3

// / -> Divisão

const divisao = 10 / 2

// *  -> Multiplicação

const multiplicacao = 2 * 10

// %  -> Resto

const resto = 11 % 2    // Nessa exemplo o  resto é 1

// ++ -> Incremento

let incremento = 5
incremento++            // Acrescenta +1 (Mesma coisa de colocar "incremento = incremento + 1") 

// -- -> Decremento

let decremento = 5
decremento--          // Tira -1 (Mesma coisa de colocar "decremento = decremento - 1") 

// ** -> Exponencial

let exponencial = 2 ** 3    // Mesma coisa de eu fazer "exponencial = 2 * 2 * 2"