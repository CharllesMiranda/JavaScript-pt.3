const numero = 17

// a) O dobro do número

const dobro = numero * 2
console.log(dobro)

// b) O triplo

const triplo = numero * 3 
console.log(triplo)

// c) O quadrado

const quadrado = numero ** 2
console.log(quadrado)

// d) O resto da divisão por 5

const resto = numero % 5
console.log(resto)

// e) O número dividido por 2

const dividido = numero / 2
console.log(dividido)